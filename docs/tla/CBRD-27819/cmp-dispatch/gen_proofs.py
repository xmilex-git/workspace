def exact(a, b):
    return (a == "NUMERIC" and b in INTS) or (b == "NUMERIC" and a in INTS)
def generic(t):
    return ("generic", t, False)
def exact_cmp(s0, s1):
    return ("exact", s0, False) if s1 == "NUMERIC" else ("exact", s1, True)
def dcc(s0, s1, compared):
    return exact_cmp(s0, s1) if exact(s0, s1) else generic(compared)
def decide(c, a, b):
    skip = c == "new" and exact(a, b)
    tgt = a if RANK[a] >= RANK[b] else b
    conv = (0, 0) if a == b or skip else (0 if a == tgt else 1, 0 if b == tgt else 1)
    after0 = tgt if conv[0] == 1 else a
    cmp = dcc(a, b, after0) if c == "new" and conv == (0, 0) else generic(after0)
    return ("DIRECT" if conv == (0, 0) else "CONVERT", (a, b), conv, tgt, cmp)
def unpack(d):
    m, s, conv, t, _ = d
    compared = t if conv[0] == 1 else s[0]
    cmp = dcc(s[0], s[1], compared) if conv == (0, 0) else generic(compared)
    return (m, s, conv, t, cmp)
def mirror(d):
    m, s, conv, t, _ = d
    compared = t if conv[1] == 1 else s[1]
    cmp = dcc(s[1], s[0], compared) if conv == (0, 0) else generic(compared)
    return (m, (s[1], s[0]), (conv[1], conv[0]), t, cmp)
def lit(d):
    m, s, conv, t, (k, ct, nf) = d
    return (f'[method |-> "{m}", src |-> <<"{s[0]}", "{s[1]}">>, conv |-> <<{conv[0]}, {conv[1]}>>, '
            f'target |-> "{t}", cmp |-> [kind |-> "{k}", type |-> "{ct}", numFirst |-> {"TRUE" if nf else "FALSE"}]]')

