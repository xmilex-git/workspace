#!/usr/bin/env python3
# usage: nlb2tla.py <Name>=<logfile>:jt=<inner|left>:pass=<k1.1,k1.2,...>[:drop=<a>:<k>|:dup=<a>:<k>|:how=<k>:<how>] ...
#        > BatchJoinTraceData.tla
#
# Turns the TLATRACE lines an instrumented build wrote during a batched nested-loop join over the model's own
# tables (five outer rows with the keys k1 k2 k1 k3 k2; three inner rows for k1, one for k2) into the sequence of
# events BatchJoinTrace consumes.  The join type and the inner rows the statement's filter accepts are the run's
# (given here: the statement decides them).
#   :drop=<a>:<k>  leaves out the k-th event of action <a>     (a corrupted run the spec must refuse)
#   :dup=<a>:<k>   repeats the k-th event of action <a>
#   :how=<k>:<h>   says the k-th row was answered by <h> (memo | slice | scan)
import sys

MARK = "TLATRACE"


def events(path):
    out = []
    with open(path, errors="replace") as f:
        for line in f:
            i = line.find(MARK)
            if i < 0:
                continue
            out.append(dict(kv.split("=", 1) for kv in line[i + len(MARK):].split() if "=" in kv))
    out.sort(key=lambda e: int(e["seq"]))
    return out


def convert(path):
    evs = events(path)
    xs = [e["x"] for e in evs if e["a"] in ("Hold", "Pass")]
    if not xs:
        sys.exit(f"{path}: no outer row reached a batching scan")
    x = xs[0]
    if any(v != x for v in xs):
        sys.exit(f"{path}: more than one batching scan; record a two-table join")
    recs = []
    armed = False
    pending = None            # an Open or Pass record waiting for how its row was answered
    passed = None             # the outer row joined at once, until its RowDone
    for k, e in enumerate(evs):
        a = e["a"]
        if a in ("MemoHit", "TakeSlice", "Scan"):
            if pending is not None and (a != "MemoHit" or e["x"] == x):
                pending["how"] = {"MemoHit": "memo", "TakeSlice": "slice", "Scan": "scan"}[a]
                pending = None
            continue
        if a == "MemoClear":
            # the storage is also cleared when the statement ends or the plan runs again: only a clear
            # between two events of the join is memoize giving up
            rest = [f["a"] for f in evs[k + 1:] if f.get("x") == x and f["a"] not in ("MemoClear",)]
            if e["x"] == x and recs and rest and rest[0] != "Arm" and recs[-1]["a"] != "Restart":
                if pending is not None:
                    # memoize gave up when the row path asked it for this row: before the row was answered
                    recs.insert(len(recs) - 1, {"a": "MemoDrop"})
                else:
                    recs.append({"a": "MemoDrop"})
            continue
        if e.get("x") != x:
            continue
        if a == "Arm":
            if armed:
                recs.append({"a": "Restart"})
            armed = True
        elif a == "Hold":
            recs.append({"a": "Hold", "o": int(e["o"]), "kind": e["kind"]})
        elif a == "Pass":
            pending = {"a": "Pass", "o": int(e["o"]), "how": "?"}
            passed = int(e["o"])
            recs.append(pending)
        elif a == "Close":
            recs.append({"a": "Close"})
        elif a == "Open":
            pending = {"a": "Open", "o": int(e["o"]), "how": "?"}
            recs.append(pending)
        elif a == "Emit":
            recs.append({"a": "Emit", "o": int(e["o"])})
        elif a == "RowDone":
            recs.append({"a": "RowDone", "o": int(e["o"])})
            if passed == int(e["o"]):
                recs.append({"a": "EndBatch"})
                passed = None
        elif a == "EndBatch":
            recs.append({"a": "EndBatch"})
        elif a == "Error":
            recs.append({"a": "Stop"})
    bad = [r for r in recs if r.get("how") == "?"]
    if bad:
        sys.exit(f"{path}: row {bad[0]['o']} has no record of how it was answered")
    return recs


def corrupt(recs, spec):
    kind, _, arg = spec.partition("=")
    a, _, n = arg.partition(":")
    if kind == "how":
        rows = [r for r in recs if r["a"] in ("Open", "Pass")]
        rows[int(a) - 1]["how"] = n
        return recs
    idx = [i for i, r in enumerate(recs) if r["a"] == a][int(n) - 1]
    if kind == "drop":
        return recs[:idx] + recs[idx + 1:]
    if kind == "dup":
        return recs[:idx + 1] + [dict(recs[idx])] + recs[idx + 1:]
    sys.exit(f"unknown corruption {spec}")


def rec_t(r):
    return ('[a |-> "%s", o |-> %d, kind |-> "%s", how |-> "%s"]'
            % (r["a"], r.get("o", 0), r.get("kind", "-"), r.get("how", "-")))


def main():
    print("----------------------- MODULE BatchJoinTraceData -----------------------")
    print("\\* generated by traces/join/nlb2tla.py; do not edit")
    print("EXTENDS TLC, Sequences")
    for arg in sys.argv[1:]:
        name, _, rest = arg.partition("=")
        parts = rest.split(":")
        path, opts = parts[0], parts[1:]
        jt, passed, corr = "inner", [], None
        i = 0
        while i < len(opts):
            o = opts[i]
            if o.startswith("jt="):
                jt = o[3:]
            elif o.startswith("pass="):
                passed = [p for p in o[5:].split(",") if p]
            else:
                corr = o + ":" + opts[i + 1]
                i += 1
            i += 1
        recs = convert(path)
        if corr:
            recs = corrupt(recs, corr)
        print()
        print("\\* %s: %s%s" % (name, path, (" (" + corr + ")") if corr else ""))
        print('%s_Jt == "%s"' % (name, jt))
        print("%s_Pass == {%s}" % (name, ", ".join('<<"%s", %s>>' % tuple(p.split(".")) for p in passed)))
        print("%s_Log == <<" % name)
        print(",\n".join("  " + rec_t(r) for r in recs))
        print(">>")
    print("=============================================================================")


main()
