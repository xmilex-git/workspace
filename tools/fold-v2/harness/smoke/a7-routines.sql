CREATE OR REPLACE FUNCTION a7f (x INT) RETURN INT AS
  n INT;
BEGIN
  SELECT COUNT(*) INTO n FROM a7t WHERE id <= x;
  RETURN n;
END;

CREATE OR REPLACE FUNCTION a7g (x INT) RETURN INT AS
  n INT;
BEGIN
  SELECT id INTO n FROM a7e WHERE id = x;
  RETURN n;
EXCEPTION
  WHEN NO_DATA_FOUND THEN
    RETURN -1;
END;

CREATE OR REPLACE FUNCTION a7h (x INT) RETURN INT AS
  n INT;
BEGIN
  SELECT a7f (x) INTO n FROM dual;
  RETURN n;
END;

CREATE OR REPLACE FUNCTION a7r (x INT) RETURN INT AS
BEGIN
  RETURN 0;
END;

CREATE OR REPLACE FUNCTION a7r (x INT) RETURN INT AS
  n INT;
BEGIN
  IF x <= 0 THEN
    RETURN 0;
  END IF;
  SELECT a7r (x - 1) INTO n FROM dual;
  RETURN n + 1;
END;

CREATE OR REPLACE PROCEDURE a7c () AS
BEGIN
  FOR r IN (SELECT id FROM a7t ORDER BY id) LOOP
    INSERT INTO a7l VALUES (r.id);
    COMMIT;
  END LOOP;
END;

CREATE OR REPLACE FUNCTION a7n (x INT) RETURN INT AS
  n INT;
BEGIN
  INSERT INTO a7cnt VALUES (x);
  SELECT COUNT(*) INTO n FROM a7cnt;
  RETURN n;
END;

CREATE OR REPLACE FUNCTION a7p (x INT) RETURN INT DETERMINISTIC PARALLEL_ENABLE AS
BEGIN
  RETURN x + 1;
END;
