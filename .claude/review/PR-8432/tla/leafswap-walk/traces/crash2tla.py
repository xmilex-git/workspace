#!/usr/bin/env python3
"""crash2tla.py <log> <Module> -- the crash-retry run of PR 8432 (h2 repro on the instrumented head) as the data module of
OvfDirChainTrace: the key's state at the KeyDump just before the Swap (leaf objects, chain pages, directory), the events
on that key (Swap, CrashAfterSwap, FindMiss and FindWalk of an object of the key), and the key's state at the first
KeyDump after the FindWalk. OIDs become their rank in (volid, pageid, slotid) order, pages 1..n in chain order."""
import sys
def toks(line):
    i = line.find("TLATRACE")
    return dict(t.partition("=")[::2] for t in line[i + 8:].split()) if i >= 0 else None
def oid(s):
    v, p, sl = s.split("|"); return (int(v), int(p), int(sl))
def vpid(s):
    v, p = s.split("|"); return (int(v), int(p))
ev = [t for t in (toks(l) for l in open(sys.argv[1])) if t]
# file order: the restart resets seq, the file is appended in execution order
dumps, cur = [], None
for i, t in enumerate(ev):
    if t["a"] == "KeyDump":
        if t["part"] == "leaf": cur = {"i": i, "leaf": [oid(x) for x in t["oids"].split(",") if x], "pages": [], "dir": []}
        elif t["part"] == "page": cur["pages"].append((vpid(t["page"]), [oid(x) for x in t["oids"].split(",") if x]))
        elif t["part"] == "dir": cur["dir"].append([(oid(e.split("@")[0]), vpid(e.split("@")[1])) for e in t["ents"].split(",") if e])
        elif t["part"] == "end": dumps.append(cur)
si = next(i for i, t in enumerate(ev) if t["a"] == "Swap")
swap = ev[si]
before = [d for d in dumps if d["i"] < si and vpid(swap["page"]) in [p for p, _ in d["pages"]]][-1]
keyobjs = set(before["leaf"]) | {o for _, os in before["pages"] for o in os}
pgs = {p: k + 1 for k, (p, _) in enumerate(before["pages"])}
recs = []
wi = None
for i, t in enumerate(ev[si:], si):
    a = t["a"]
    if a == "Swap" and i == si:
        recs.append('[a |-> "Swap", moved |-> %s, deleted |-> %s, page |-> %d]' % ("M", "D", pgs[vpid(t["page"])]))
    elif a == "CrashAfterSwap":
        recs.append('[a |-> "CrashAfterSwap"]')
    elif a == "FindMiss" and oid(t["oid"]) in keyobjs:
        recs.append('[a |-> "FindMiss", o |-> %s, routed |-> %d]' % (oid(t["oid"]), pgs.get(vpid(t["routed"]), 0)))
    elif a == "FindWalk" and oid(t["oid"]) in keyobjs:
        recs.append('[a |-> "FindWalk", o |-> %s, page |-> %d, found |-> %s]' % (oid(t["oid"]), pgs.get(vpid(t["page"]), 0), t["found"]))
        wi = i
after = next(d for d in dumps if wi is not None and d["i"] > wi and set(p for p, _ in d["pages"]) & set(pgs))
allo = keyobjs | {o for _, os in after["pages"] for o in os} | set(after["leaf"]) | {s for dp in before["dir"] for s, _ in dp}
rank = {o: k + 1 for k, o in enumerate(sorted(allo))}
O = lambda o: "<<%d, 1>>" % rank[o]
fix = lambda r: r.replace('moved |-> M', 'moved |-> %d' % rank[oid(swap["moved"])]).replace('deleted |-> D', 'deleted |-> %d' % rank[oid(swap["deleted"])])
out = []
for r in recs:
    r = fix(r)
    if " o |-> (" in r:
        s = r.split(" o |-> ")[1].split(", ", 3)
        tup = "(%s, %s, %s)" % (s[0][1:], s[1], s[2].rstrip(")"))
        r = r.replace(" o |-> " + tup, " o |-> %d" % rank[eval(tup)])
    out.append(r)
apg = {p: k + 1 for k, (p, _) in enumerate(after["pages"])}
print("---- MODULE %s ----" % sys.argv[2])
print("\\* Generated by traces/crash2tla.py from %s; OIDs are ranks in (volid, pageid, slotid) order" % sys.argv[1].split("/")[-1])
print("EXTENDS Naturals, Sequences")
print("TNOid == %d" % len(rank))
print("TPageCap == %d" % max(len(os) for _, os in before["pages"] + after["pages"]))
print("TLeaf == {%s}" % ", ".join(O(o) for o in before["leaf"]))
print("TChain == <<%s>>" % ", ".join(str(k + 1) for k in range(len(before["pages"]))))
print("TPages == <<%s>>" % ",\n  ".join("<<%s>>" % ", ".join(O(o) for o in os) for _, os in before["pages"]))
print("TDir == <<%s>>" % ", ".join("<<%s>>" % ", ".join("[sep |-> %d, pg |-> %d]" % (rank[s], pgs[p]) for s, p in dp) for dp in before["dir"]))
print("TLeafAfter == {%s}" % ", ".join(O(o) for o in after["leaf"]))
print("TFlatAfter == <<%s>>" % ", ".join(O(o) for _, os in after["pages"] for o in os))
print("CrashTrace == <<\n  %s\n>>" % ",\n  ".join(out))
print("====")
sys.stderr.write("objects=%d pages=%d dirpages=%d events=%s\n" % (len(rank), len(before["pages"]), len(before["dir"]), [r.split(",")[0] for r in out]))
