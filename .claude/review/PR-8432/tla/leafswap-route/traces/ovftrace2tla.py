#!/usr/bin/env python3
"""ovftrace2tla.py <log> <ModuleName> [<Result lost=N dups=M>] -- turn an instrumented CBRD-24094 run into the
data module of OvfScanResumeTrace (PR 8432 review copy; reject log = merge-base swap page): the scanned key's state at KeyDump time (leaf objects, chain pages, directory)
and the events on that key's chain, with OIDs replaced by their rank in (volid, pageid, slotid) order and page ids
by 1..n in chain order (directory pages are not model pages).  The key traced is the dumped key whose chain holds
the page of the ScanStop event."""
import re, sys

def toks(line):
    i = line.find("TLATRACE")
    return dict(t.partition("=")[::2] for t in line[i + 8:].split()) if i >= 0 else None

def oid(s):
    v, p, sl = s.split("|"); return (int(v), int(p), int(sl))

def vpid(s):
    v, p = s.split("|"); return (int(v), int(p))

ev = [t for t in (toks(l) for l in open(sys.argv[1])) if t]
ev.sort(key=lambda t: int(t["seq"]))
dumps, cur = [], None
for t in ev:
    if t["a"] == "KeyDump":
        if t["part"] == "leaf": cur = {"leaf": [oid(x) for x in t["oids"].split(",") if x], "pages": [], "dir": []}
        elif t["part"] == "page": cur["pages"].append((vpid(t["page"]), [oid(x) for x in t["oids"].split(",") if x]))
        elif t["part"] == "dir":
            cur["dir"].append([(oid(e.split("@")[0]), vpid(e.split("@")[1])) for e in t["ents"].split(",") if e])
        elif t["part"] == "end": dumps.append(cur)
stop = next(t for t in ev if t["a"] == "ScanStop")
key = next(d for d in dumps if vpid(stop["before_page"]) in [p for p, _ in d["pages"]])
pgs = {p: i + 1 for i, (p, _) in enumerate(key["pages"])}
allo = set(key["leaf"]) | {o for _, os in key["pages"] for o in os} | {s for dp in key["dir"] for s, _ in dp}
for t in ev:
    for f in ("anchor", "moved", "deleted", "moved_first", "moved_last"):
        if f in t and t[f].count("|") == 2: allo.add(oid(t[f]))
rank = {o: i + 1 for i, o in enumerate(sorted(allo))}
O = lambda o: "<<%d, 1>>" % rank[o]
recs = []
for t in ev:
    a = t["a"]
    if a == "ScanStop":
        recs.append('[a |-> "ScanStop", anchor |-> %d, before |-> %d]' % (rank[oid(t["anchor"])], pgs[vpid(t["before_page"])]))
    elif a == "Pull" and vpid(t["left"]) in pgs:
        recs.append('[a |-> "Pull", left |-> %d, right |-> %d, n |-> %s, merge |-> %s, first |-> %d, last |-> %d]'
                    % (pgs[vpid(t["left"])], pgs[vpid(t["right"])], t["nmove"], t["merge"],
                       rank[oid(t["moved_first"])], rank[oid(t["moved_last"])]))
    elif a == "Swap" and vpid(t["page"]) in pgs:
        recs.append('[a |-> "Swap", moved |-> %d, deleted |-> %d]' % (rank[oid(t["moved"])], rank[oid(t["deleted"])]))
    elif a == "Resume":
        recs.append('[a |-> "Resume", anchor |-> %d, page |-> %d, k |-> %d]'
                    % (rank[oid(t["anchor"])], pgs[vpid(t["page"])], int(t["offset"]) // 24 + 1))
if len(sys.argv) > 3:
    f = dict(x.split("=") for x in sys.argv[3].split()[1:])
    recs.append('[a |-> "Result", lost |-> %s, dups |-> %s]' % (f["lost"], f["dups"]))
print("---- MODULE %s ----" % sys.argv[2])
print("\\* Generated by traces/ovftrace2tla.py from %s; OIDs are ranks in (volid, pageid, slotid) order" % sys.argv[1].split("/")[-1])
print("EXTENDS Naturals, Sequences")
print("TNOid == %d" % len(rank))
print("TLeaf == {%s}" % ", ".join(O(o) for o in key["leaf"]))
print("TChain == <<%s>>" % ", ".join(str(i + 1) for i in range(len(key["pages"]))))
print("TPages == <<%s>>" % ", ".join("<<%s>>" % ", ".join(O(o) for o in os) for _, os in key["pages"]))
print("TDir == <<%s>>" % ", ".join("<<%s>>" % ", ".join("[sep |-> %d, pg |-> %d]" % (rank[s], pgs[p]) for s, p in dp) for dp in key["dir"]))
print("TraceLog == <<\n  %s\n>>" % ",\n  ".join(recs))
# corrupted run for the reject cfg: the swap moves the first page's last object (the merge-base swap page)
sw = next(k for k, r in enumerate(recs) if '"Swap"' in r)
p1last = rank[key["pages"][0][1][-1]]
bad = list(recs)
bad[sw] = re.sub(r"moved \|-> \d+", "moved |-> %d" % p1last, recs[sw])
assert bad[sw] != recs[sw], "the run's swap already moved the first page's last object"
print("TraceLogFirstPageSwap == <<\n  %s\n>>" % ",\n  ".join(bad))
print("====")
